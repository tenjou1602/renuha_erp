function runehaIntegerInWords(int $number): string {
    $number = abs($number);
    if ($number === 0) {
        return 'Zero';
    }
    $belowTwenty = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'];
    $tens = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];
    $chunkWords = function (int $chunk) use ($belowTwenty, $tens): string {
        $words = '';
        if ($chunk >= 100) {
            $words .= $belowTwenty[intdiv($chunk, 100)] . ' Hundred';
            $chunk %= 100;
            if ($chunk > 0) {
                $words .= ' ';
            }
        }
        if ($chunk >= 20) {
            $words .= $tens[intdiv($chunk, 10)];
            if ($chunk % 10 > 0) {
                $words .= ' ' . $belowTwenty[$chunk % 10];
            }
        } elseif ($chunk > 0) {
            $words .= $belowTwenty[$chunk];
        }
        return $words;
    };
    $chunks = [];
    while ($number > 0) {
        $chunks[] = $number % 1000;
        $number = intdiv($number, 1000);
    }
    $scales = ['', 'Thousand', 'Million', 'Billion'];
    $parts = [];
    for ($i = count($chunks) - 1; $i >= 0; $i--) {
        if ($chunks[$i] === 0) {
            continue;
        }
        $scale = $scales[$i] ?? '';
        $parts[] = trim($chunkWords($chunks[$i]) . ($scale !== '' ? ' ' . $scale : ''));
    }
    return implode(' ', $parts);
}

function runehaAmountInWords(float $amount): string {
    $negative = $amount < 0;
    $amount = round(abs($amount), 2);
    $pesos = (int) floor($amount);
    $centavos = (int) round(($amount - $pesos) * 100);
    if ($centavos === 100) {
        $pesos++;
        $centavos = 0;
    }
    $text = 'PHP ' . runehaIntegerInWords($pesos);
    if ($centavos > 0) {
        $text .= ' and ' . runehaIntegerInWords($centavos) . ' Centavos';
    }
    $text .= ' Only';
    return $negative ? 'Negative ' . $text : $text;
}

