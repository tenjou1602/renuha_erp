        $rows .= '<tr class="spacer"><td style="height:' . $spacer . 'px;"></td><td></td><td></td><td></td><td></td><td></td><td></td></tr>';
    }
    $qtyCell = $sameUnit ? runehaInvoiceQty($qtyTotal) . ($unitLabel !== '' ? ' ' . htmlspecialchars($unitLabel) : '') : '';
    $notes = trim((string) ($invoice['notes'] ?? ''));
    $words = runehaAmountInWords($amount);
    $paymentLine = '';
    if ($paid > 0) {
        $paymentLine = '<div class="pay">Amount paid: PHP ' . number_format($paid, 2) . ' &nbsp;&nbsp; Balance: PHP ' . number_format($balance, 2) . '</div>';
    }
    $tin = trim((string) ($invoice['client_tin'] ?? ''));
    $metaRows = '<tr>' . runehaCommercialMeta('Invoice No.', (string) ($invoice['invoice_number'] ?? '')) . runehaCommercialMeta('Dated', runehaFormalDate($invoice['invoice_date'] ?? '')) . '</tr>'
        . '<tr>' . runehaCommercialMeta('Quote No.', (string) ($invoice['quotation_number'] ?? '')) . runehaCommercialMeta('Due Date', runehaFormalDate($invoice['due_date'] ?? '')) . '</tr>'
        . '<tr>' . runehaCommercialMeta('Status', $status, true) . runehaCommercialMeta('Project', $project, true) . '</tr>';
    $extra = $paymentLine
        . ($notes !== '' ? '<div class="notes">Notes: ' . nl2br(htmlspecialchars($notes)) . '</div>' : '')
        . ($tin !== '' ? '<div style="margin-top:8px;">Client TIN : ' . htmlspecialchars($tin) . '</div>' : '');
    return runehaCommercialFormHtml('INVOICE', 'Consignee', $consignee, $metaRows, $rows, $qtyCell, $amount, $words, $extra);
}

function runehaPurchaseOrderStatusLabel(string $status): string {
    $labels = [
        'draft' => 'Draft',
        'sent' => 'Sent',
        'confirmed' => 'Confirmed',
        'ready_for_warehouse' => 'Ready for Warehouse',
        'delivered' => 'Delivered',
        'cancelled' => 'Cancelled',
    ];
    return $labels[$status] ?? ucfirst(str_replace('_', ' ', $status));
}

function buildPurchaseOrderReportHtml(PDO $pdo, array $order): string {
    $project = trim((string) ($order['project_code'] ?? ''));
    if (!empty($order['project_name'])) {
        $project = trim($project . ' - ' . $order['project_name'], ' -');
    }
    $supplierName = trim((string) ($order['supplier'] ?? ''));
    $companyName = trim((string) ($order['supplier_contact'] ?? ''));
    $supplierRow = null;
    if ($supplierName !== '') {
        try {
            $stmt = $pdo->prepare("SELECT name, company_name, phone, email, address, tin_number FROM suppliers WHERE LOWER(name) = LOWER(?) OR (company_name IS NOT NULL AND company_name <> '' AND LOWER(company_name) = LOWER(?)) LIMIT 1");
            $stmt->execute([$supplierName, $supplierName]);
            $supplierRow = $stmt->fetch() ?: null;
        } catch (Throwable $e) {
            $supplierRow = null;
        }
    }
    if ($companyName === '' && !empty($supplierRow['company_name'])) {
        $companyName = trim((string) $supplierRow['company_name']);
    }
    $address = trim((string) ($supplierRow['address'] ?? ''));
    $email = trim((string) ($supplierRow['email'] ?? ''));
    $phone = trim((string) ($supplierRow['phone'] ?? ''));
    $tin = trim((string) ($supplierRow['tin_number'] ?? ''));
    $contactDigits = preg_replace('/\D/', '', $companyName);
    $contactIsPhone = $contactDigits !== '' && strlen($contactDigits) >= 7;
    $contactIsEmail = strpos($companyName, '@') !== false;
    if ($contactIsPhone || $contactIsEmail || strcasecmp($companyName, $phone) === 0 || strcasecmp($companyName, $email) === 0) {
        $companyName = trim((string) ($supplierRow['company_name'] ?? ''));
    }
    $partyName = $supplierName !== '' ? $supplierName : $companyName;
    $party = '<div class="party">' . htmlspecialchars($partyName) . '</div>';
    if ($companyName !== '' && strcasecmp($companyName, $partyName) !== 0) {
        $party .= '<div>Company: ' . htmlspecialchars($companyName) . '</div>';
    }
    if ($address !== '') {
        $party .= '<div>' . nl2br(htmlspecialchars($address)) . '</div>';
    }
    if ($email !== '') {
        $party .= '<div>E-Mail: ' . htmlspecialchars($email) . '</div>';
    }
    if ($phone !== '') {
        $party .= '<div>Phone: ' . htmlspecialchars($phone) . '</div>';
    }
    $lines = [];
    try {
        $stmt = $pdo->prepare("
            SELECT COALESCE(NULLIF(m.name, ''), 'Material') AS description, m.unit, poi.quantity, poi.unit_price
            FROM purchase_order_items poi
            LEFT JOIN materials m ON m.id = poi.material_id
            WHERE poi.purchase_order_id = ?
            ORDER BY poi.id
        ");
        $stmt->execute([(int) $order['id']]);
        foreach ($stmt->fetchAll() as $line) {
            $qty = (float) ($line['quantity'] ?? 0);
            $rate = (float) ($line['unit_price'] ?? 0);
            $lines[] = [
                'description' => (string) $line['description'],
                'quantity' => $qty,
                'unit' => trim((string) ($line['unit'] ?? '')),
                'rate' => $rate,
                'amount' => $qty * $rate,
            ];
        }
    } catch (Throwable $e) {
        $lines = [];
    }
    $lineTotal = 0.0;
    foreach ($lines as $line) {
        $lineTotal += $line['amount'];
    }
    $savedTotal = round((float) ($order['total_amount'] ?? 0), 2);
    $amount = $savedTotal > 0 ? $savedTotal : round($lineTotal, 2);
    if (!$lines) {
        $lines[] = [
            'description' => 'No materials recorded',
            'quantity' => $amount > 0 ? 1 : 0,
            'unit' => $amount > 0 ? 'lot' : '',
            'rate' => $amount,
            'amount' => $amount,
        ];
    }
    $sameUnit = true;
    $unitLabel = '';
    $qtyTotal = 0.0;
    $rows = '';
    $n = 0;
    foreach ($lines as $line) {
        $n++;
        $qtyTotal += $line['quantity'];
        if ($unitLabel === '') {
            $unitLabel = $line['unit'];
        } elseif (strcasecmp($unitLabel, $line['unit']) !== 0) {
            $sameUnit = false;
        }
        $rows .= '<tr class="item">'
            . '<td class="center">' . $n . '</td>'
            . '<td>' . htmlspecialchars($line['description']) . '</td>'
            . '<td class="center">' . ($line['description'] === 'No materials recorded' && $line['quantity'] <= 0 ? '' : runehaInvoiceQty($line['quantity'])) . '</td>'
            . '<td class="right">' . number_format($line['rate'], 2) . '</td>'
            . '<td class="center">' . htmlspecialchars($line['unit']) . '</td>'
            . '<td></td>'
            . '<td class="right">' . number_format($line['amount'], 2) . '</td>'
            . '</tr>';
    }
    $spacer = max(0, 8 - count($lines)) * 18;
    if ($spacer > 0) {
        $rows .= '<tr class="spacer"><td style="height:' . $spacer . 'px;"></td><td></td><td></td><td></td><td></td><td></td><td></td></tr>';
    }
    $qtyCell = $sameUnit ? runehaInvoiceQty($qtyTotal) . ($unitLabel !== '' ? ' ' . htmlspecialchars($unitLabel) : '') : '';
    $terms = trim((string) ($order['payment_terms'] ?? ''));
    $extra = $terms !== '' ? '<div class="notes">Payment terms: ' . htmlspecialchars($terms) . '</div>' : '';
    if ($tin !== '') {
        $extra .= '<div style="margin-top:8px;">Supplier TIN : ' . htmlspecialchars($tin) . '</div>';
    }
    $metaRows = '<tr>' . runehaCommercialMeta('PO No.', (string) ($order['po_number'] ?? '')) . runehaCommercialMeta('Order Date', runehaFormalDate($order['order_date'] ?? '')) . '</tr>'
        . '<tr>' . runehaCommercialMeta('PR No.', (string) ($order['pr_number'] ?? '')) . runehaCommercialMeta('Delivery', runehaFormalDate($order['delivery_date'] ?? '')) . '</tr>'
        . '<tr>' . runehaCommercialMeta('Status', runehaPurchaseOrderStatusLabel((string) ($order['status'] ?? '')), true) . runehaCommercialMeta('Project', $project, true) . '</tr>';
    return runehaCommercialFormHtml('PURCHASE ORDER', 'Supplier', $party, $metaRows, $rows, $qtyCell, $amount, runehaAmountInWords($amount), $extra);
}
