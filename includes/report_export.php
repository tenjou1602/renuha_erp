}

function runehaPdfInfo(array $pairs): string {
    $html = '<table class="info">';
    $cells = [];
    foreach ($pairs as $pair) {
        $cells[] = '<div class="label">' . htmlspecialchars((string) $pair[0]) . '</div><div class="value">' . $pair[1] . '</div>';
    }
    for ($i = 0; $i < count($cells); $i += 2) {
        $html .= '<tr><td>' . $cells[$i] . '</td><td>' . ($cells[$i + 1] ?? '') . '</td></tr>';
    }
    return $html . '</table>';
}

function runehaPdfTable(array $headers, array $rows, ?array $total = null): string {
    $html = '<table class="data"><thead><tr>';
    foreach ($headers as $header) {
        $html .= '<th>' . htmlspecialchars((string) $header) . '</th>';
    }
    $html .= '</tr></thead><tbody>';
    if (!$rows) {
        $html .= '<tr><td class="empty" colspan="' . count($headers) . '">No records yet.</td></tr>';
    }
    foreach ($rows as $index => $row) {
        $html .= '<tr' . ($index % 2 === 1 ? ' class="alt"' : '') . '>';
        foreach ($row as $cell) {
            $html .= '<td>' . $cell . '</td>';
        }
        $html .= '</tr>';
    }
    if ($total) {
        $html .= '<tr class="total">';
        foreach ($total as $cell) {
            $html .= '<td>' . $cell . '</td>';
        }
        $html .= '</tr>';
    }
    return $html . '</tbody></table>';
}

