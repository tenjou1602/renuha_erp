function runehaInvoiceLines(PDO $pdo, array $invoice): array {
    $lines = [];
    $push = function (string $description, $quantity, string $unit, $rate, $amount) use (&$lines): void {
        $description = trim($description);
        if ($description === '') {
            $description = 'Item';
        }
        $lines[] = [
            'description' => $description,
            'quantity' => (float) $quantity,
            'unit' => trim($unit),
            'rate' => (float) $rate,
            'amount' => (float) $amount,
        ];
    };
    try {
        $stmt = $pdo->prepare("SELECT description, quantity, unit, unit_price, line_total FROM invoice_items WHERE invoice_id = ? ORDER BY id");
        $stmt->execute([(int) $invoice['id']]);
        foreach ($stmt->fetchAll() as $line) {
            $push((string) ($line['description'] ?? ''), $line['quantity'] ?? 0, (string) ($line['unit'] ?? ''), $line['unit_price'] ?? 0, $line['line_total'] ?? 0);
        }
    } catch (Throwable $e) {
        $lines = [];
    }
    if (!$lines && !empty($invoice['quotation_id'])) {
        try {
            $stmt = $pdo->prepare("SELECT description, quantity, unit, unit_price, line_total FROM client_quotation_items WHERE quotation_id = ? ORDER BY id");
            $stmt->execute([(int) $invoice['quotation_id']]);
            foreach ($stmt->fetchAll() as $line) {
                $push((string) ($line['description'] ?? ''), $line['quantity'] ?? 0, (string) ($line['unit'] ?? ''), $line['unit_price'] ?? 0, $line['line_total'] ?? 0);
            }
        } catch (Throwable $e) {
            $lines = [];
        }
    }
    if (!$lines && !empty($invoice['procurement_quotation_id'])) {
        try {
            $stmt = $pdo->prepare("
                SELECT COALESCE(NULLIF(m.name, ''), NULLIF(m.description, ''), m.material_code, 'Item') AS description,
                       qi.quantity, qi.unit, qi.unit_price
                FROM quotation_items qi
                LEFT JOIN materials m ON m.id = qi.material_id
                WHERE qi.quotation_id = ?
                ORDER BY qi.id
            ");
            $stmt->execute([(int) $invoice['procurement_quotation_id']]);
            foreach ($stmt->fetchAll() as $line) {
                $qty = (float) ($line['quantity'] ?? 0);
                $rate = (float) ($line['unit_price'] ?? 0);
                $push((string) ($line['description'] ?? ''), $qty, (string) ($line['unit'] ?? ''), $rate, $qty * $rate);
            }
        } catch (Throwable $e) {
            $lines = [];
        }
    }
    if (!$lines) {
        $description = trim((string) ($invoice['project_name'] ?? ''));
        if ($description === '') {
            $description = trim((string) ($invoice['invoice_number'] ?? 'Invoice'));
        }
        $push($description, 1, 'lot', $invoice['amount'] ?? 0, $invoice['amount'] ?? 0);
    }
    return $lines;
}

function runehaInvoiceQty($quantity): string {
    $quantity = (float) $quantity;
    if (abs($quantity - round($quantity)) < 0.001) {
        return number_format($quantity, 0);
    }
    return number_format($quantity, 2);
}

